package javaBasicStructure;

//Problem #2: Write a program that prints your name and age.
//Expected Output: [your name] + [age]

public class NameAndAge {
	public static void main(String[] args) {
		
		// Declaration - You can change the variable below, with your name  
		String name= "Henry "; 
		int age = 19; 
		
		//Output - the message that prints in the console.
		System.out.println("Name: " + name); 
		System.out.println("Age: " + age);
		}
// Discussion This program declares two variables, one for a name and one for an age, and prints them to the console. 
}
