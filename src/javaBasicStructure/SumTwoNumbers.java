package javaBasicStructure;

//Problem #3: Write a program that displays the sum of two numbers.
//Expected Output: The added two numbers you input.

public class SumTwoNumbers {
	public static void main(String[] args) {
		
		//Declaration - You can change the num1, and num2 with your desired numbers. leave the res equal to 0.
		int num1=100, num2=32, res=0; 
		
		//Process - Addition
		res = num1 + num2;
		
		//Output 
		System.out.print("The sum of two numbers is equal to " + res + "."); 
		}
	
// Discussion: This program calculates the sum of two integers and displays the result. It introduces basic arithmetic operations in Java and shows how to store the computed value in a variable before printing.
}
