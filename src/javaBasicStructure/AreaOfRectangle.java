package javaBasicStructure;

// Problem# 8: Write a program to print the area of a rectangle (length width).
// Expected Output: [Area of a Rectangle] - with your inputted numbers in length and width.

public class AreaOfRectangle {
	public static void main(String[] args) {
		
		// Declaration 
		int length= 3, width =6, area=0;
		
		//Process 
		area = length * width;
		
		//Output 
		System.out.println("The area of a rectangle is equal to " + area + "."); 
		
		}
// Discussion: This program calculates the area of a rectangle using the formula length × width.
}
