package javaBasicStructure;

// Problem #6: Write a program that prints your name in uppercase letters.
// Expected Ouput: [YOUR NAME] - in uppercase
public class NameUppercaseLetters {
	public static void main(String[] args) {
		//Declaration
		String name = " Henry"; 
		
		//Output, uses .toUpperCase method
		System.out.println(name.toUpperCase());
	}
	
// Discussion : This program stores a name in a String variable and prints it in uppercase using the toUpperCase() method. It demonstrates Java’s built-in string manipulation methods for formatting text output.

}
