package javaBasicStructure;

// Problem #4: Write a program to print the product of three numbers.
// Expected Output: The multiplied three numbers you input.

public class ProductThreeNumbers {
	public static void main(String[] args) {
		
		//Declaration 
		int num1=12, num2=32, num3=21, product=0; 
		
		//Process 
		product = num1 * num2 * num3;
		
		//Output 
		System.out.print("The product of three numbers is equal to " + product + "."); 
		}
	
// Discussion: This program multiplies three integers to find their product and prints the result.
}
